    /**
     * @return array{0: int, 1: bool}  [timestamp_utc, from_lookup]
     */
    public static function getEquinoxUTC(int $gYear): array
    {
        $table = self::getEquinoxLookup();

        if (isset($table[$gYear])) {
            [$m, $d, $h, $min, $sec] = $table[$gYear];
            return [gmmktime($h, $min, $sec, $m, $d, $gYear), true];
        }

        $jde = self::vernalEquinoxJDE($gYear);
        return [self::jdeToTimestamp($jde, $gYear), false];
    }

