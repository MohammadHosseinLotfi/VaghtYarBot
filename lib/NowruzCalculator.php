    /**
     * محاسبه JDE اعتدال بهاری — فصل ۲۷ کتاب Astronomical Algorithms
     */
    public static function vernalEquinoxJDE(int $year): float
    {
        $Y = ($year - 2000) / 1000.0;

        $JDE0 = 2451623.80984
              + 365242.37404 * $Y
              +      0.05169 * $Y * $Y
              -      0.00411 * $Y * $Y * $Y
              -      0.00057 * $Y * $Y * $Y * $Y;

        $T = ($JDE0 - 2451545.0) / 36525.0;
        $W = deg2rad(35999.373 * $T - 2.47);
        $dL = 1.0 + 0.0334 * cos($W) + 0.0007 * cos(2.0 * $W);

        // ۲۴ جمله تناوبی (جدول ۲۷.c)
        $terms = [
            [485, 324.96, 1934.136], [203, 337.23, 32964.467], [199, 342.08,    20.186],
            [182,  27.85, 445267.112],[156,  73.14,  45036.886], [136, 171.52, 22518.443],
            [ 77, 222.54,  65928.934],[ 74, 296.72,   3034.906], [ 70, 243.58,  9037.513],
            [ 58, 119.81,  33718.147],[ 52, 297.17,    150.678], [ 50,  21.02,  2281.226],
            [ 45, 247.54,  29929.562],[ 44, 325.15,  31555.956], [ 29,  60.93,  4443.417],
            [ 18, 155.12,  67555.328],[ 17, 288.79,   4562.452], [ 16, 198.04, 62894.029],
            [ 14, 199.76,  31436.921],[ 12,  95.39,  14577.848], [ 12, 287.11, 31931.756],
            [ 12, 320.81,  34777.259],[  9, 227.73,   1222.114], [  8,  15.45, 16859.074],
        ];

        $S = 0.0;
        foreach ($terms as [$A, $B, $C]) {
            $S += $A * cos(deg2rad($B + $C * $T));
        }

        return $JDE0 + (0.00001 * $S) / $dL;
    }

    /**
     * Delta T (TT − UT) بر حسب ثانیه — تقریب Espenak-Meeus
     */
    public static function deltaT(int $year): float
    {
        $t = $year - 2000;

        if ($year >= 2005 && $year <= 2050) {
            return 62.92 + 0.32217 * $t + 0.005589 * $t * $t;
        }
        if ($year >= 2000) {
            return 63.83 + 0.1 * ($year - 2000);
        }
        $u = ($year - 1820) / 100.0;
        return -20 + 32 * $u * $u;
    }

    /**
     * JDE → Unix Timestamp (UTC)
     */
    private static function jdeToTimestamp(float $jde, int $year): int
    {
        $dt   = self::deltaT($year);
        $jdUT = $jde - ($dt / 86400.0);
        return (int) round(($jdUT - 2440587.5) * 86400.0);
    }

