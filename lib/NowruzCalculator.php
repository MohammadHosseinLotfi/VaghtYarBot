    /**
     * میلادی → شمسی (جلالی)
     * @return array{0: int, 1: int, 2: int}  [jy, jm, jd]
     */
    public static function toJalali(int $gy, int $gm, int $gd): array
    {
        $gdm  = [0, 31, 59, 90, 120, 151, 181, 212, 243, 273, 304, 334];
        $gy2  = ($gm > 2) ? $gy + 1 : $gy;
        $days = 355666
              + 365 * $gy
              + intdiv($gy2 + 3,   4)
              - intdiv($gy2 + 99,  100)
              + intdiv($gy2 + 399, 400)
              + $gd
              + $gdm[$gm - 1];

        $jy    = -1595 + 33 * intdiv($days, 12053);
        $days %= 12053;

        $jy   += 4 * intdiv($days, 1461);
        $days %= 1461;

        if ($days > 365) {
            $jy   += intdiv($days - 1, 365);
            $days  = ($days - 1) % 365;
        }

        if ($days < 186) {
            $jm = 1 + intdiv($days, 31);
            $jd = 1 + $days % 31;
        } else {
            $jm = 7  + intdiv($days - 186, 30);
            $jd = 1  + ($days - 186) % 30;
        }

        return [$jy, $jm, $jd];
    }

    /**
     * میلادی → هجری قمری (تقویم جدولی اسلامی)
     * @return array{0: int, 1: int, 2: int}  [hy, hm, hd]
     */
    public static function toHijri(int $gy, int $gm, int $gd): array
    {
        $y = $gy;
        $m = $gm;
        $d = $gd;

        if ($m <= 2) { $y--; $m += 12; }

        $A  = intdiv($y, 100);
        $B  = 2 - $A + intdiv($A, 4);
        $jd = (int) floor(365.25  * ($y + 4716))
            + (int) floor(30.6001 * ($m + 1))
            + $d + $B - 1524;

        $l = $jd - 1948440 + 10632;
        $n = intdiv($l - 1, 10631);
        $l = $l - 10631 * $n + 354;

        $j = intdiv(10985 - $l, 5316) * intdiv(50 * $l, 17719)
           + intdiv($l, 5670)          * intdiv(43 * $l, 15238);

        $l = $l
           - intdiv(30 - $j, 15) * intdiv(17719 * $j, 50)
           - intdiv($j, 16)      * intdiv(15238 * $j, 43)
           + 29;

        $hm = intdiv(24 * $l, 709);
        $hd = $l - intdiv(709 * $hm, 24);
        $hy = 30 * $n + $j - 30;

        return [$hy, $hm, $hd];
    }

    /**
     * بررسی کبیسه بودن سال شمسی — چرخه ۲۸۲۰ ساله (الگوریتم احمد بیرشک)
     */
    public static function isJalaliLeap(int $jy): bool
    {
        $leapMods = [1, 5, 9, 13, 17, 22, 26, 30];
        $mod      = (($jy + 2346) % 2820) % 33;
        return in_array($mod, $leapMods, true);
    }

